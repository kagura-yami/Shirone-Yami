import { readFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { Store } from './storage.mjs';
import { provider } from './auth.mjs';
import { createApp } from './app.mjs';
process.umask(0o077);
const config=JSON.parse(readFileSync(process.env.CONFIG_FILE ?? '/run/secrets/config.json','utf8'));
if(!['admin','vault'].includes(config.mode) || !config.subject || !config.origin?.startsWith('https://') || !config.sessionSecret || !config.clientSecret) throw new Error('Invalid production configuration');
config.secure=true;
config.queue='/queue'; config.results='/results';
config.media='/data/media';config.source='/legacy';config.sourcePublic='/source-public';
mkdirSync('/data',{recursive:true});
const key=config.mode==='vault'?Buffer.from(readFileSync('/run/secrets/vault-key','utf8').trim(),'hex'):undefined;
const store=new Store(path.join('/data','content.sqlite3'),config.mode,key);
if(config.mode==='admin')console.log(`Imported ${store.importSource('/legacy')} existing blog entries`);
const identity=await provider(config);
const {app}=createApp(config,store,identity);
const server=app.listen(8080,'0.0.0.0',()=>console.log(`Authoring ${config.mode} ready`));
server.requestTimeout=15000;server.headersTimeout=10000;
